package com.taskallocator.model;

import java.util.ArrayList;
import java.util.List;

/**
 * =====================================================================
 * Member 1 Responsibility: Team Member & Skill Management
 * =====================================================================
 * The Member class represents a student team member in the college project.
 * Demonstrates OOP Encapsulation:
 * - Attributes are declared private to protect internal state.
 * - Public getter and setter methods provide controlled access.
 */
public class Member {

    private int memberId;
    private String name;
    private String email;
    private String role;
    private List<String> skills;

    /**
     * Default no-argument constructor.
     */
    public Member() {
        this.skills = new ArrayList<>();
    }

    /**
     * Constructor used when adding a new member (ID is generated by MySQL).
     *
     * @param name  Full name of the member
     * @param email College email address
     * @param role  Project role (e.g., 'Project Leader' or 'Team Member')
     */
    public Member(String name, String email, String role) {
        this.name = name;
        this.email = email;
        this.role = role;
        this.skills = new ArrayList<>();
    }

    /**
     * Full constructor for reconstructing a member record loaded from the database.
     *
     * @param memberId Database primary key
     * @param name     Full name
     * @param email    Email
     * @param role     Role
     */
    public Member(int memberId, String name, String email, String role) {
        this.memberId = memberId;
        this.name = name;
        this.email = email;
        this.role = role;
        this.skills = new ArrayList<>();
    }

    // Getters and Setters demonstrating Encapsulation

    public int getMemberId() {
        return memberId;
    }

    public void setMemberId(int memberId) {
        this.memberId = memberId;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getRole() {
        return role;
    }

    public void setRole(String role) {
        this.role = role;
    }

    public List<String> getSkills() {
        return skills;
    }

    public void setSkills(List<String> skills) {
        this.skills = (skills != null) ? skills : new ArrayList<>();
    }

    /**
     * Adds a skill to this member's skill list if not already present.
     *
     * @param skill Skill name (e.g., 'Java Programming')
     */
    public void addSkill(String skill) {
        if (skill != null && !skill.trim().isEmpty() && !skills.contains(skill.trim())) {
            this.skills.add(skill.trim());
        }
    }

    /**
     * Checks if this member has the specified skill (case-insensitive).
     *
     * @param requiredSkill Skill to check
     * @return true if the member possesses the skill, false otherwise
     */
    public boolean hasSkill(String requiredSkill) {
        if (requiredSkill == null) return false;
        for (String s : skills) {
            if (s.equalsIgnoreCase(requiredSkill.trim())) {
                return true;
            }
        }
        return false;
    }

    /**
     * Returns skills formatted as a comma-separated string for easy table display.
     */
    public String getSkillsFormatted() {
        if (skills == null || skills.isEmpty()) {
            return "None";
        }
        return String.join(", ", skills);
    }

    @Override
    public String toString() {
        return name + " (" + role + ")";
    }
}
